        private static readonly string[] RankNames = { "C", "C+", "B", "B+", "A", "A+", "S" };

        public static int Count => RankMasks.Length;

        public static IReadOnlyList<string> AvailableRanks(int index)
        {
            byte mask = Mask(index);
            var result = new List<string> { "None" };
            for (int bit = 0; bit < RankNames.Length; bit++)
                if ((mask & (1 << bit)) != 0)
                    result.Add(RankNames[bit]);
            return result;
        }

        public static string MaxRank(int index)
        {
            byte mask = Mask(index);
            for (int bit = RankNames.Length - 1; bit >= 0; bit--)
                if ((mask & (1 << bit)) != 0)
                    return RankNames[bit];
            return "None";
        }

        public static int MaxRankPoints(int index)
        {
            string rank = MaxRank(index);
            if (rank == "None")
                throw new ArgumentException("This support entry has no conversations.", nameof(index));
            return SupportRankPresets.PointsFor(rank);
        }

        public static string RankForPoints(int index, int points)
        {
            byte mask = Mask(index);
            string result = "None";
            for (int bit = 0; bit < RankNames.Length; bit++)
                if ((mask & (1 << bit)) != 0 && points >= SupportRankPresets.PointsFor(RankNames[bit]))
                    result = RankNames[bit];
            return result;
        }

        public static int PointsFor(int index, string rank)
        {
            byte mask = Mask(index);
            if (string.Equals(rank, "None", StringComparison.OrdinalIgnoreCase))
                return 0;
            for (int bit = 0; bit < RankNames.Length; bit++)
                if (string.Equals(rank, RankNames[bit], StringComparison.OrdinalIgnoreCase)
                    && (mask & (1 << bit)) != 0)
                    return SupportRankPresets.PointsFor(RankNames[bit]);
            throw new ArgumentException($"Support entry {index} does not have rank {rank}.", nameof(rank));
        }

        private static byte Mask(int index)
        {
            if ((uint)index >= RankMasks.Length)
                throw new ArgumentOutOfRangeException(nameof(index));
            return RankMasks[index];
        }
